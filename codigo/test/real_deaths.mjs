import puppeteer from "puppeteer-core";
import path from "node:path";
const browser = await puppeteer.launch({ executablePath: "/usr/bin/google-chrome", headless: "new", args: ["--no-sandbox", "--allow-file-access-from-files"] });
const page = await browser.newPage();
await page.setViewport({ width: 1600, height: 1000 });
const errors = [];
page.on("pageerror", (e) => errors.push(e.message));
await page.goto("file://" + path.resolve("dist/local.html"), { waitUntil: "load" });
await page.waitForSelector(".kpi");
await page.evaluate(() => { location.hash = "importacao"; });
await new Promise((r) => setTimeout(r, 300));
await (await page.$("#imp-file")).uploadFile(process.argv[2]);
await page.waitForFunction(() => document.querySelector(".callout.good"), { timeout: 60000 });
await page.select("#f-period", "all");
await page.evaluate(() => { location.hash = "mortes"; });
await new Promise((r) => setTimeout(r, 900));
const kpi = await page.evaluate(() => document.querySelector(".kpi.hero")?.innerText.replace(/\s+/g, " "));
const types = await page.evaluate(() => [...document.querySelectorAll(".card")].find((c) => c.innerText.includes("Mortes antes de objetivos, por tipo"))?.querySelectorAll("tbody")[0].innerText.split("\n").slice(0, 12));
await page.evaluate(() => [...document.querySelectorAll(".card")].find((c) => c.innerText.includes("Mortes antes de objetivos, por tipo")).querySelectorAll("tbody")[1].querySelector("tr").click());
await new Promise((r) => setTimeout(r, 700));
const drawer = await page.evaluate(() => ({ open: !!document.querySelector(".drawer"), sel: document.querySelector(".drawer .chip[aria-pressed='true']")?.innerText, callout: document.querySelector(".drawer .callout")?.innerText }));
await page.keyboard.press("Escape");
await page.evaluate(() => { location.hash = "coach"; });
await new Promise((r) => setTimeout(r, 900));
const coach = await page.evaluate(() => [...document.querySelectorAll(".diag-head")].map((d) => d.innerText.replace(/\s+/g, " ")));
await page.evaluate(() => { location.hash = "evolucao"; });
await new Promise((r) => setTimeout(r, 500));
const evo = await page.evaluate(() => [...document.querySelectorAll("tbody tr")].map((tr) => tr.innerText.split("\t")[0]).filter((x) => /Pick/.test(x)));
console.log(JSON.stringify({ kpi, types, drawer, coach, evo, errors }, null, 1));
await browser.close();
