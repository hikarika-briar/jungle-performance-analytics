import puppeteer from "puppeteer-core";
import path from "node:path";
const [dataFile, refsFile, outDir] = process.argv.slice(2);
const browser = await puppeteer.launch({ executablePath: "/usr/bin/google-chrome", headless: "new", args: ["--no-sandbox", "--allow-file-access-from-files"] });
const page = await browser.newPage();
await page.setViewport({ width: 1366, height: 1000 });
const errors = [];
page.on("pageerror", (e) => errors.push(e.message));
await page.goto("file://" + path.resolve("dist/local.html"), { waitUntil: "load" });
await page.waitForSelector(".kpi");
await page.evaluate(() => { location.hash = "importacao"; });
await new Promise((r) => setTimeout(r, 300));
await (await page.$("#imp-file")).uploadFile(dataFile);
await page.waitForFunction(() => document.querySelector(".callout.good"), { timeout: 60000 });
await (await page.$("#imp-file")).uploadFile(refsFile);
await page.waitForFunction(() => [...document.querySelectorAll(".callout.good")].some((c) => c.innerText.includes("referência")), { timeout: 90000 });
// Coach Analítico
await page.evaluate(() => { location.hash = "coach"; });
await new Promise((r) => setTimeout(r, 1200));
const coach = await page.evaluate(() => ({ report: document.querySelector(".card")?.innerText.slice(0, 600), diags: [...document.querySelectorAll(".diag-head")].map((d) => d.innerText.replace(/\s+/g, " ")) }));
const rep = await page.$(".card");
await rep.screenshot({ path: outDir + "/v7_coach_report.png" });
const firstStrength = await page.evaluateHandle(() => [...document.querySelectorAll(".diag")].find((d) => d.innerText.includes("PONTO FORTE")));
if (firstStrength.asElement()) await firstStrength.asElement().screenshot({ path: outDir + "/v7_strength.png" });
const red = await page.evaluateHandle(() => [...document.querySelectorAll(".diag")].find((d) => d.innerText.includes("Mortes em sequência")));
if (red.asElement()) await red.asElement().screenshot({ path: outDir + "/v7_redeaths.png" });
// Challenger
await page.evaluate(() => { location.hash = "rumo-challenger"; });
await new Promise((r) => setTimeout(r, 1500));
const gc = await page.evaluateHandle(() => [...document.querySelectorAll(".card")].find((c) => c.innerText.includes("Coach Challenger")));
await gc.asElement().screenshot({ path: outDir + "/v7_chcoach.png" });
const ch = await page.evaluate(() => ({ focus: [...document.querySelectorAll(".diag h3")].map((h) => h.innerText), kpis: [...document.querySelectorAll(".kpi")].map((k) => k.innerText.replace(/\s+/g, " ")) }));
await page.select("#ch-champ", "noLee");
await new Promise((r) => setTimeout(r, 900));
const noLee = await page.evaluate(() => document.querySelector(".callout").innerText.slice(0, 140));
await page.select("#ch-champ", "all");
await new Promise((r) => setTimeout(r, 600));
const strip = await page.evaluateHandle(() => [...document.querySelectorAll(".card")].find((c) => c.innerText.includes("Onde você está entre")));
await strip.asElement().screenshot({ path: outDir + "/v7_strip.png" });
await page.setViewport({ width: 400, height: 900 });
await new Promise((r) => setTimeout(r, 600));
const mobile = await page.evaluate(() => ({ sw: document.documentElement.scrollWidth, cw: document.documentElement.clientWidth }));
console.log(JSON.stringify({ coach, ch, noLee, mobile, errors }, null, 1));
await browser.close();
