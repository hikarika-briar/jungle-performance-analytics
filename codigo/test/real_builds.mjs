import puppeteer from "puppeteer-core";
import path from "node:path";
const browser = await puppeteer.launch({ executablePath: "/usr/bin/google-chrome", headless: "new", args: ["--no-sandbox", "--allow-file-access-from-files"] });
const page = await browser.newPage();
await page.setViewport({ width: 1600, height: 1000 });
const errors = [];
page.on("pageerror", (e) => errors.push(e.message));
await page.goto("file://" + path.resolve("dist/local.html"), { waitUntil: "load" });
await page.waitForSelector(".kpi");
await page.evaluate(() => { location.hash = "importacao"; });
await new Promise((r) => setTimeout(r, 300));
await (await page.$("#imp-file")).uploadFile(process.argv[2]);
await page.waitForFunction(() => document.querySelector(".callout.good"), { timeout: 60000 });
await page.evaluate(() => { location.hash = "builds"; });
await new Promise((r) => setTimeout(r, 600));
const callout = await page.evaluate(() => !!document.querySelector(".callout.warn"));
await page.evaluate(() => [...document.querySelectorAll("button")].find((b) => b.textContent.includes("Usar todo o histórico"))?.click());
await new Promise((r) => setTimeout(r, 800));
const ranking = await page.evaluate(() => [...document.querySelectorAll(".card")][0].querySelectorAll("tbody tr").length);
const rows = await page.evaluate(() => [...[...document.querySelectorAll(".card")][0].querySelectorAll("tbody tr")].map((tr) => [...tr.querySelectorAll("td")].slice(1, 4).map((td) => td.innerText.replace(/\s+/g, " ")).join(" | ")));
const duel = async (label) => {
  await page.evaluate((l) => [...document.querySelectorAll(".chip")].find((b) => b.textContent === l)?.click(), label);
  await new Promise((r) => setTimeout(r, 500));
  return page.evaluate(() => ({ sides: [...document.querySelectorAll(".bc-side")].map((s) => s.querySelector(".sample")?.textContent + " · " + s.querySelector(".bignum")?.textContent), notes: [...document.querySelectorAll(".notes li")].map((li) => li.textContent.slice(0, 110)) }));
};
const d1 = await duel("Eclipse × Dança da Morte no 4º item");
const d2 = await duel("Build do Eclipse × Hidra › Cutelo › Dança");
await page.evaluate(() => [...document.querySelectorAll("button")].find((b) => b.textContent === "Editar builds")?.click());
await new Promise((r) => setTimeout(r, 300));
const editors = await page.evaluate(() => document.querySelectorAll("[id^='bc-r']").length);
await page.screenshot({ path: process.argv[3], fullPage: false });
console.log(JSON.stringify({ callout, ranking, rows, d1, d2, editors, errors }, null, 1));
await browser.close();
