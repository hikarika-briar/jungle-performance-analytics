import puppeteer from "puppeteer-core";
import path from "node:path";
const browser = await puppeteer.launch({ executablePath: "/usr/bin/google-chrome", headless: "new", args: ["--no-sandbox", "--allow-file-access-from-files"] });
const page = await browser.newPage();
await page.setViewport({ width: 1440, height: 1000 });
const errors = [];
page.on("pageerror", (e) => errors.push(e.message));
await page.goto("file://" + path.resolve("dist/local.html"), { waitUntil: "load" });
await page.waitForSelector(".kpi");
await page.evaluate(() => { location.hash = "importacao"; });
await new Promise((r) => setTimeout(r, 300));
await (await page.$("#imp-file")).uploadFile(process.argv[2]);
await page.waitForFunction(() => document.querySelector(".callout.good"), { timeout: 60000 });
await page.evaluate(() => { location.hash = "coach"; });
await new Promise((r) => setTimeout(r, 1200));
console.log("ERR", JSON.stringify(errors), await page.evaluate(() => [...document.querySelectorAll(".card h2, .card h3, .card .title")].map((h) => h.innerText).join(" / ")));
const card = await page.evaluateHandle(() => [...document.querySelectorAll(".card")].find((c) => c.innerText.includes("Revisão de derrotas")));
const info = await card.evaluate((c) => ({ kpis: [...c.querySelectorAll(".kpi")].map((k) => k.innerText.replace(/\s+/g, " ")), rows: [...c.querySelectorAll("tbody")].pop().innerText.split("\n").slice(0, 6), w: c.scrollWidth, cw: c.clientWidth }));
await card.evaluate((c) => c.scrollIntoView());
await new Promise((r) => setTimeout(r, 300));
await card.screenshot({ path: process.argv[3] + "/loss_review.png" });
await page.select("#lr-sig", "1");
await new Promise((r) => setTimeout(r, 300));
const filtered = await card.evaluate((c) => [...c.querySelectorAll("tbody")].pop().querySelectorAll("tr").length);
await card.evaluate((c) => [...c.querySelectorAll("tbody")].pop().querySelector("tr").click());
await new Promise((r) => setTimeout(r, 700));
const drawer = await page.evaluate(() => !!document.querySelector(".drawer"));
await page.keyboard.press("Escape");
await page.setViewport({ width: 400, height: 900 });
await new Promise((r) => setTimeout(r, 500));
const mobile = await page.evaluate(() => ({ sw: document.documentElement.scrollWidth, cw: document.documentElement.clientWidth }));
console.log(JSON.stringify({ info, filtered, drawer, mobile, errors }, null, 1));
await browser.close();
