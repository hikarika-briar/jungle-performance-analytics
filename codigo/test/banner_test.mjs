// Troca o fundo do banner pela imagem dada, ajusta o enquadramento e fotografa.
import puppeteer from "puppeteer-core";
import path from "node:path";
const [dataFile, imgFile, outDir, zoom = "100", x = "50", y = "30", width = "1440"] = process.argv.slice(2);
const browser = await puppeteer.launch({ executablePath: "/usr/bin/google-chrome", headless: "new", args: ["--no-sandbox", "--allow-file-access-from-files"] });
const page = await browser.newPage();
await page.setViewport({ width: Number(width), height: 1000 });
const errors = [];
page.on("pageerror", (e) => errors.push(e.message));
await page.goto("file://" + path.resolve("dist/local.html"), { waitUntil: "load" });
await page.waitForSelector(".nav");
await page.evaluate(() => { location.hash = "importacao"; });
await new Promise((r) => setTimeout(r, 600));
await (await page.$("#imp-file")).uploadFile(dataFile);
await page.waitForFunction(() => document.querySelector(".callout.good"), { timeout: 90000 });
await page.evaluate(() => { location.hash = "visao-geral"; });
await new Promise((r) => setTimeout(r, 1200));
await page.click(".banner-edit > .btn");
await new Promise((r) => setTimeout(r, 300));
await (await page.$("#banner-file")).uploadFile(imgFile);
await page.waitForSelector("#banner-zoom", { timeout: 20000 });
const setRange = (sel, v) => page.$eval(sel, (el, v) => { const set = Object.getOwnPropertyDescriptor(HTMLInputElement.prototype, "value").set; set.call(el, v); el.dispatchEvent(new Event("input", { bubbles: true })); }, v);
await setRange("#banner-zoom", zoom); await setRange("#banner-x", x); await setRange("#banner-y", y);
await new Promise((r) => setTimeout(r, 500));
await (await page.$(".banner")).screenshot({ path: `${outDir}/banner_edit_${width}.png` });
await page.evaluate(() => [...document.querySelectorAll(".banner-panel button")].find((b) => b.textContent === "Salvar").click());
await new Promise((r) => setTimeout(r, 1200));
await (await page.$(".banner")).screenshot({ path: `${outDir}/banner_saved_${width}.png` });
const st = await page.evaluate(() => ({ img: document.querySelector(".hero-bg img")?.style.cssText, panel: !!document.querySelector(".banner-panel"), sw: document.documentElement.scrollWidth }));
console.log(JSON.stringify({ st, errors }));
await browser.close();
