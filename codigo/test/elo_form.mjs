// Abre "Marcar um mês", adiciona e remove uma marcação, e fotografa o gráfico.
import puppeteer from "puppeteer-core";
import path from "node:path";
const [dataFile, outDir] = process.argv.slice(2);
const browser = await puppeteer.launch({ executablePath: "/usr/bin/google-chrome", headless: "new", args: ["--no-sandbox", "--allow-file-access-from-files"] });
const page = await browser.newPage();
await page.setViewport({ width: 1440, height: 1100 });
const errors = [];
page.on("pageerror", (e) => errors.push(e.message));
await page.goto("file://" + path.resolve("dist/local.html"), { waitUntil: "load" });
await page.waitForSelector(".nav");
await page.evaluate(() => { location.hash = "importacao"; });
await new Promise((r) => setTimeout(r, 600));
await (await page.$("#imp-file")).uploadFile(dataFile);
await page.waitForFunction(() => document.querySelector(".callout.good"), { timeout: 90000 });
await page.evaluate(() => { location.hash = "visao-geral"; });
await new Promise((r) => setTimeout(r, 1500));
const before = await page.evaluate(() => document.querySelectorAll(".elo-chip").length);
const clickByText = (t) => page.evaluate((t) => { const b = [...document.querySelectorAll("button")].find((x) => x.textContent.trim() === t); b?.click(); return !!b; }, t);
await clickByText("Marcar um mês");
await new Promise((r) => setTimeout(r, 300));
await page.$eval("#elo-month", (el) => { const set = Object.getOwnPropertyDescriptor(HTMLInputElement.prototype, "value").set; set.call(el, "2026-03"); el.dispatchEvent(new Event("input", { bubbles: true })); });
await page.select("#elo-tier", "EMERALD");
await page.select("#elo-div", "I");
await page.type("#elo-lp", "45");
await clickByText("Adicionar");
await new Promise((r) => setTimeout(r, 800));
const chips = await page.evaluate(() => [...document.querySelectorAll(".elo-chip")].map((c) => c.textContent));
const sub = await page.evaluate(() => [...document.querySelectorAll(".tile")].find((t) => t.textContent.includes("Elo mês a mês"))?.querySelector(".tile-head, header")?.textContent);
const el = await page.evaluateHandle(() => [...document.querySelectorAll(".tile")].find((t) => t.textContent.includes("Elo mês a mês")));
await new Promise((r) => setTimeout(r, 600));
await el.screenshot({ path: `${outDir}/elo_form_open.png` });
await page.evaluate(() => document.querySelector('.elo-chip button[aria-label="Remover mar/26"]')?.click());
await new Promise((r) => setTimeout(r, 600));
const after = await page.evaluate(() => [...document.querySelectorAll(".elo-chip")].map((c) => c.textContent));
await clickByText("Fechar");
await new Promise((r) => setTimeout(r, 300));
const closed = await page.evaluate(() => document.querySelectorAll(".elo-chip").length);
console.log(JSON.stringify({ before, chips, sub, after, closed, errors }));
await browser.close();
